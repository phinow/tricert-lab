import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:3000/#learn');
await page.waitForSelector('.hero-session, .learn');
await page.click('.nav button:has(.nav-label:text-is("Plan"))');
const t0 = Date.now();
await page.click('.plan .week-detail li >> nth=0 >> button');
await page.waitForSelector('.reader .read');
console.log('lesson opened in', Date.now() - t0, 'ms; sections', await page.locator('.read').count());
await page.click('.finished >> nth=1 >> summary');
assert.ok((await page.textContent('.finished >> nth=1')).length > 1500);
await page.click('.nav button:has(.nav-label:text-is("Learn"))');
await page.click('.segmented button:has-text("Documents")');
await page.click('.doc-list li >> nth=3 >> button');
await page.waitForSelector('.finished-fold');
console.log('document guide present');
assert.deepEqual(errors, []);
console.log('ok, no console errors');
await browser.close();
